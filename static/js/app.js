/**
 * ========================================================================================
 * ТОЛСТЫЙ КЛИЕНТ: ТОЧКА ВХОДА ПРИЛОЖЕНИЯ В БРАУЗЕРЕ (static/js/app.js)
 * ========================================================================================
 * 
 * Данный скрипт запускается при полной загрузке структуры DOM (событие DOMContentLoaded).
 * Он связывает все подсистемы толстого клиента воедино:
 * 1. Проверяет наличие сохраненного JWT-токена в памяти браузера (localStorage).
 * 2. Если токен есть, запрашивает у сервера актуальный профиль через GET /api/auth/me.
 * 3. Генерирует навигационную панель в зависимости от роли вошедшего пользователя.
 * 4. Запускает маршрутизатор Router, который отрисовывает начальный экран.
 * ========================================================================================
 */

document.addEventListener('DOMContentLoaded', async () => {
    // 1. Проверка сессии пользователя по ранее сохраненному JWT
    if (API.getToken()) {
        try {
            await API.getMe();
        } catch (e) {
            console.log('Пользователь не авторизован или токен устарел/отозван.');
        }
    }

    // 2. Первоначальный рендеринг шапки сайта
    UI.renderNavbar();

    // 3. Запуск маршрутизатора (откроет экран по текущему адресу или #home)
    Router.init();
});
